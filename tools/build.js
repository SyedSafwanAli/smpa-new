// Inject partials/header.html, partials/footer.html and the shared head and
// script tags (partials/head.html, partials/scripts.html) into every page.
//
// The pages stay complete, servable HTML — nothing is assembled at request
// time — but the header and footer now have a single source. Change
// partials/, run `node tools/build.js`, and all pages follow.
//
// First run wraps each page's existing header/footer block in markers; later
// runs just replace what sits between them.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

// Which nav entry each page lights up, and which dropdown it sits under.
const NAV = {
  'index.html':                   { key: 'home' },
  'about.html':                   { key: 'about',        group: 'about' },
  'history.html':                 { key: 'history',      group: 'about' },
  'management-organogram.html':   { key: 'management',   group: 'about' },
  'officers-directory.html':      { key: 'officers',     group: 'about' },
  'offices.html':                 { key: 'offices',      group: 'about' },
  'master-plans.html':            { key: 'master-plans', group: 'plans' },
  'permits-procedures-fee.html':  { key: 'permits',      group: 'services' },
  'laws.html':                    { key: 'laws',         group: 'legal' },
  'reports.html':                 { key: 'reports',      group: 'legal' },
  'notifications.html':           { key: 'notifications', group: 'legal' },
  'projects-studies.html':        { key: 'projects' },
  'tenders.html':                 { key: 'tenders',       group: 'services' },
  'careers.html':                 { key: 'careers',       group: 'services' },
  'approved-schemes.html':        { key: 'approved-schemes' },
  'news/index.html':              { key: 'latest-news' },
  'news/press-releases.html':     { key: 'press-releases' },
  // Rendered notices light up Notifications in the Laws & Notifications menu.
  'notices/*':                    { key: 'notifications' },
};

const HEADER_OPEN  = '<!-- @partial header — generated by tools/build.js; edit partials/header.html -->';
const HEADER_CLOSE = '<!-- @end header -->';
const FOOTER_OPEN  = '<!-- @partial footer — generated by tools/build.js; edit partials/footer.html -->';
const FOOTER_CLOSE = '<!-- @end footer -->';

// Legacy boundaries, used only to place the markers the first time.
const LEGACY_HEADER_START = '<!-- ============================================================\n     1) TOP UTILITY BAR';
const LEGACY_FOOTER_START = '<!-- ============================================================\n     15) FOOTER';

// Shared <head> assets (fonts, design-system stylesheet) and the closing
// scripts. First run inserts them before </head> and </body>.
const HEAD_OPEN     = '<!-- @partial head — generated by tools/build.js; edit partials/head.html -->';
const HEAD_CLOSE    = '<!-- @end head -->';
const SCRIPTS_OPEN  = '<!-- @partial scripts — generated by tools/build.js; edit partials/scripts.html -->';
const SCRIPTS_CLOSE = '<!-- @end scripts -->';

const headSrc    = fs.readFileSync(path.join(ROOT, 'partials', 'head.html'), 'utf8');
const scriptsSrc = fs.readFileSync(path.join(ROOT, 'partials', 'scripts.html'), 'utf8');
const headerSrc = fs.readFileSync(path.join(ROOT, 'partials', 'header.html'), 'utf8');
const footerSrc = fs.readFileSync(path.join(ROOT, 'partials', 'footer.html'), 'utf8');

function render(src, base, nav) {
  let out = src.split('{{BASE}}').join(base);
  if (!nav) return out;

  // Light up the page's own entry — in the desktop menu and the drawer both.
  if (nav.key) {
    const re = new RegExp(`(<a class=")([^"]*)("[^>]*?data-nav="${nav.key}")`, 'g');
    out = out.replace(re, (_, a, cls, rest) => `${a}${cls} active${rest} aria-current="page"`);
  }
  // ...and the menu it lives under: the desktop trigger is marked current and
  // the matching mobile <details> group starts open.
  if (nav.group) {
    const trig = new RegExp(`(data-nav-group="${nav.group}">\\s*<button class="nav__trigger)"`);
    out = out.replace(trig, '$1 is-current"');
    out = out.replace(`<details class="mnav__group" data-nav-group="${nav.group}">`,
                      `<details class="mnav__group" data-nav-group="${nav.group}" open>`);
  }
  return out;
}

function splice(html, open, close, legacyStart, legacyEnd, block, file) {
  const marked = html.indexOf(open);
  if (marked >= 0) {
    const end = html.indexOf(close, marked);
    if (end < 0) throw new Error(`${file}: ${open} has no matching ${close}`);
    return html.slice(0, marked) + open + '\n' + block + close + html.slice(end + close.length);
  }
  // No markers and no legacy block: insert just before the closing tag.
  if (legacyStart === null) {
    const at = html.lastIndexOf(legacyEnd);
    if (at < 0) throw new Error(`${file}: no ${legacyEnd}`);
    return html.slice(0, at) + open + '\n' + block + close + '\n' + html.slice(at);
  }
  // No markers yet — find the hand-written block and replace it wholesale.
  const a = html.indexOf(legacyStart);
  const b = html.indexOf(legacyEnd, a);
  if (a < 0 || b < 0) throw new Error(`${file}: could not locate block (${a}, ${b})`);
  return html.slice(0, a) + open + '\n' + block + close + '\n\n' + html.slice(b);
}

// Folders of pages that sit one level down. Each renders with base '../'.
const SUBDIRS = ['news', 'notices'];

const targets = [
  ...fs.readdirSync(ROOT).filter(f => f.endsWith('.html')),
  ...SUBDIRS.flatMap(dir => fs.existsSync(path.join(ROOT, dir))
    ? fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith('.html')).map(f => path.join(dir, f))
    : []),
];

let changed = 0;
for (const rel of targets) {
  const file = path.join(ROOT, rel);
  const sub = SUBDIRS.find(d => rel.startsWith(d + path.sep));
  const base = sub ? '../' : '';
  // Keyed by path, not basename: news/index.html would otherwise collide with
  // the homepage and light up Home instead of Latest News.
  const relKey = rel.split(path.sep).join('/');
  // A page in news/ sits in the News dropdown and a page in notices/ under
  // Laws & Notifications; the listing pages also light their own entry.
  const GROUP = { news: 'media', notices: 'legal' };
  const nav = sub
    ? Object.assign({ group: GROUP[sub] }, NAV[relKey] || NAV[sub + '/*'] || {})
    : NAV[relKey];

  const before = fs.readFileSync(file, 'utf8');
  let html = before;

  html = splice(html, HEADER_OPEN, HEADER_CLOSE, LEGACY_HEADER_START, '<main>',
                render(headerSrc, base, nav), rel);
  html = splice(html, FOOTER_OPEN, FOOTER_CLOSE, LEGACY_FOOTER_START, '<script src="https://cdn.jsdelivr.net',
                render(footerSrc, base, null), rel);

  html = splice(html, HEAD_OPEN, HEAD_CLOSE, null, '</head>', render(headSrc, base, null), rel);
  html = splice(html, SCRIPTS_OPEN, SCRIPTS_CLOSE, null, '</body>', render(scriptsSrc, base, null), rel);

  if (html !== before) { fs.writeFileSync(file, html); changed++; console.log(`  updated  ${rel}`); }
  else console.log(`  ok       ${rel}`);
}
console.log(`\n${targets.length} pages, ${changed} rewritten`);
